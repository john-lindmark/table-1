#!/usr/bin/env python3
"""Mana symbols for every client (contract/insights-2026-10-24.md § The Limited page "Pips").

tools/mana/svg holds Scryfall's card symbols (https://svgs.scryfall.io/card-symbols/<name>.svg, every symbol that
appears in mana costs, read from https://api.scryfall.com/symbology on 2026-11-09). This writes them out for each
client and the shared parse cases:

  iOS      apps/ios/Table1/Resources/Assets.xcassets/Mana/mana-<name>.imageset (the SVG, vector data kept)
  web      table-1-events-web/public/mana/<name>.svg
  Android  apps/android/app/src/main/res/drawable/mana_<name>.xml (VectorDrawables) and ManaSymbols.kt's names
  cases    testdata/mana-symbols/cases.json (ManaSymbols.parse: a mana cost → symbol names)

  python3 -I tools/mana/make.py
"""
import json
import os
import re
import shutil
import xml.etree.ElementTree as ET

TOP = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(TOP, "tools/mana/svg")
NS = "{http://www.w3.org/2000/svg}"


def names():
    return sorted(f[:-4] for f in os.listdir(SRC) if f.endswith(".svg"))


def parse(cost):
    """'{2}{W}{U/B}' → ['2', 'W', 'UB']; a second face's cost after ' // ' → '//' then its symbols."""
    out = []
    for i, face in enumerate((cost or "").split(" // ")):
        if i:
            out.append("//")
        out += [s.replace("/", "").upper() for s in re.findall(r"\{([^}]+)\}", face)]
    return out


def ios(all_names):
    root = os.path.join(TOP, "apps/ios/Table1/Resources/Assets.xcassets/Mana")
    shutil.rmtree(root, ignore_errors=True)
    os.makedirs(root)
    with open(os.path.join(root, "Contents.json"), "w") as f:
        json.dump({"info": {"author": "xcode", "version": 1}}, f, indent=2)
    for n in all_names:
        d = os.path.join(root, f"mana-{n}.imageset")
        os.makedirs(d)
        shutil.copy(os.path.join(SRC, f"{n}.svg"), os.path.join(d, f"{n}.svg"))
        with open(os.path.join(d, "Contents.json"), "w") as f:
            json.dump({"images": [{"filename": f"{n}.svg", "idiom": "universal"}], "info": {"author": "xcode", "version": 1},
                       "properties": {"preserves-vector-representation": True}}, f, indent=2)


def web(all_names):
    d = os.path.join(TOP, "table-1-events-web/public/mana")
    shutil.rmtree(d, ignore_errors=True)
    os.makedirs(d)
    for n in all_names:
        shutil.copy(os.path.join(SRC, f"{n}.svg"), os.path.join(d, f"{n}.svg"))


def circle(cx, cy, r):
    return f"M{cx - r},{cy}a{r},{r} 0 1,0 {2 * r},0a{r},{r} 0 1,0 {-2 * r},0Z"


def vector(svg):
    """One SVG (a <g> of circles and paths, or bare paths) as a VectorDrawable."""
    root = ET.parse(svg).getroot()
    out = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by tools/mana/make.py from Scryfall's card symbol. -->",
           '<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="18dp" android:height="18dp" '
           'android:viewportWidth="100" android:viewportHeight="100">']

    def shapes(parent, rule, alpha, indent):
        for e in parent:
            tag = e.tag.replace(NS, "")
            fill = e.get("fill")
            r = e.get("fill-rule", rule)
            if tag == "g":
                t = re.match(r"translate\(([-\d.]+)[ ,]+([-\d.]+)\)", e.get("transform", "")) if e.get("transform") else None
                op = float(e.get("opacity", "1")) * alpha
                if t:
                    out.append(f'{indent}<group android:translateX="{t.group(1)}" android:translateY="{t.group(2)}">')
                    shapes(e, e.get("fill-rule", rule), op, indent + "  ")
                    out.append(f"{indent}</group>")
                else:
                    shapes(e, e.get("fill-rule", rule), op, indent)
                continue
            if tag == "circle":
                d = circle(float(e.get("cx")), float(e.get("cy")), float(e.get("r")))
            elif tag == "path":
                d = e.get("d")
            else:
                raise SystemExit(f"{svg}: unexpected <{tag}>")
            if not fill or fill == "none":
                continue
            attrs = [f'android:pathData="{d}"', f'android:fillColor="{fill.upper() if len(fill) == 7 else expand(fill)}"']
            if r == "evenodd":
                attrs.append('android:fillType="evenOdd"')
            if alpha < 1:
                attrs.append(f'android:fillAlpha="{alpha}"')
            out.append(f"{indent}<path {' '.join(attrs)} />")

    shapes(root, "nonzero", 1.0, "  ")
    out.append("</vector>")
    return "\n".join(out) + "\n"


def expand(hex3):
    return "#" + "".join(ch * 2 for ch in hex3[1:]).upper()


def android(all_names):
    res = os.path.join(TOP, "apps/android/app/src/main/res/drawable")
    for f in os.listdir(res):
        if f.startswith("mana_"):
            os.remove(os.path.join(res, f))
    for n in all_names:
        with open(os.path.join(res, f"mana_{n.lower()}.xml"), "w") as f:
            f.write(vector(os.path.join(SRC, f"{n}.svg")))
    kt = os.path.join(TOP, "apps/android/app/src/main/java/site/table1/events/insights/ManaSymbolsData.kt")
    rows = ",\n".join(f'        "{n}" to R.drawable.mana_{n.lower()}' for n in all_names)
    with open(kt, "w") as f:
        f.write("// Generated by tools/mana/make.py: the bundled mana symbols (Scryfall's card symbols).\n"
                "package site.table1.events.insights\n\nimport site.table1.events.R\n\n"
                "internal object ManaSymbolsData {\n    val drawables: Map<String, Int> = mapOf(\n" + rows + ",\n    )\n}\n")


def cases(all_names):
    costs = ["{2}{W}", "{W}{U}", "{X}{R}{R}", "{1}{U/B}{U/B}", "{2/W}{2/W}", "{G/U/P}", "{W/P}", "{C}", "{S}", "{0}",
             "{16}", "", "{1}{R} // {2}{U}", "{3}{U} // {B}", "{HW}", "{1000000}", "{w}{u}"]
    d = os.path.join(TOP, "testdata/mana-symbols")
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "cases.json"), "w") as f:
        json.dump({"about": "ManaSymbols.parse(cost) → symbol names (tools/mana/make.py). `symbols` is every symbol each client bundles; "
                            "a name outside it draws as a plain grey circle with its text.",
                   "symbols": all_names, "cases": [{"cost": c, "want": parse(c)} for c in costs]}, f, indent=1)
        f.write("\n")


def main():
    all_names = names()
    ios(all_names)
    web(all_names)
    android(all_names)
    cases(all_names)
    print(f"{len(all_names)} symbols")


if __name__ == "__main__":
    main()

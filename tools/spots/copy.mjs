// Writes the store listings from marketing/bundle/spots/spots.json to marketing/store/*.md. Run by run.sh.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { LIMITS, appStoreListing, playListing, screenshotOrder } from "./storeCopy.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const file = JSON.parse(readFileSync(`${ROOT}/marketing/bundle/spots/spots.json`, "utf8"));
const out = `${ROOT}/marketing/store`;
mkdirSync(out, { recursive: true });

const a = appStoreListing(file);
const p = playListing(file);
const over = [];
const check = (what, text, limit) => { if (text.length > limit) over.push(`${what}: ${text.length} > ${limit}`); };
check("App Store name", a.name, LIMITS.appStore.name);
check("App Store subtitle", a.subtitle, LIMITS.appStore.subtitle);
check("App Store promotional text", a.promotionalText, LIMITS.appStore.promotionalText);
check("App Store description", a.description, LIMITS.appStore.description);
check("App Store keywords", a.keywords, LIMITS.appStore.keywords);
check("Play title", p.title, LIMITS.play.title);
check("Play short description", p.shortDescription, LIMITS.play.shortDescription);
check("Play full description", p.fullDescription, LIMITS.play.fullDescription);
if (over.length) { console.error("Store copy over its limits:\n  " + over.join("\n  ")); process.exit(1); }

const shots = screenshotOrder(file).map((s) => `${s.n}. \`${s.n}-${s.key}.png\` — ${s.headline}`).join("\n");
const head = `<!-- Generated by tools/spots/copy.mjs from marketing/bundle/spots/spots.json (${file.updated}). Edit the JSON, not this file. -->`;

writeFileSync(`${out}/app-store.md`, `${head}
# App Store listing

Paste into App Store Connect → App Information / the version page. Screenshots: \`marketing/store/appstore/\` (6.9-inch, 1320×2868), in this order:

${shots}

## Name (${a.name.length}/${LIMITS.appStore.name})
${a.name}

## Subtitle (${a.subtitle.length}/${LIMITS.appStore.subtitle})
${a.subtitle}

## Promotional text (${a.promotionalText.length}/${LIMITS.appStore.promotionalText})
${a.promotionalText}

## Description (${a.description.length}/${LIMITS.appStore.description})
${a.description}

## Keywords (${a.keywords.length}/${LIMITS.appStore.keywords})
${a.keywords}
`);

writeFileSync(`${out}/google-play.md`, `${head}
# Google Play listing

Paste into Play Console → Main store listing. Phone screenshots: \`marketing/store/play/\` (1080×1920), in this order; feature graphic \`marketing/store/feature/feature.png\` (1024×500).

${shots}

## App name (${p.title.length}/${LIMITS.play.title})
${p.title}

## Short description (${p.shortDescription.length}/${LIMITS.play.shortDescription})
${p.shortDescription}

## Full description (${p.fullDescription.length}/${LIMITS.play.fullDescription})
${p.fullDescription}
`);
console.log(`Store copy written: app-store.md (${a.description.length} chars), google-play.md (${p.fullDescription.length} chars)`);
